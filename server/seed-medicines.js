// ── Seed ────────────────────────────────────────────────────────────────────────
async function seed() {
  try {
    await mongoose.connect(process.env.MONGODB_URI);
    console.log('✅ Connected to MongoDB');

    // 1. Upsert categories
    const categoryMap = {};
    for (const cat of CATEGORIES) {
      const doc = await Category.findOneAndUpdate(
        { name: cat.name },
        { $set: { description: cat.description, isActive: true } },
        { upsert: true, new: true }
      );
      categoryMap[cat.name] = doc._id;
      console.log(`  📂 Category: ${cat.name}`);
    }

    // 2. Upsert medicines
    let count = 0;
    for (const [catName, meds] of Object.entries(MEDICINES_BY_CATEGORY)) {
      const categoryId = categoryMap[catName];
      for (const med of meds) {
        await Medicine.findOneAndUpdate(
          { name: med.name },
          { $set: { ...med, category: categoryId, isActive: true } },
          { upsert: true, new: true }
        );
        count++;
        console.log(`  💊 ${med.name}`);
      }
    }

    console.log(`\n✅ Seeding complete — ${CATEGORIES.length} categories, ${count} medicines`);
    await mongoose.disconnect();
    process.exit(0);
  } catch (err) {
    console.error('❌ Seed error:', err.message);
    process.exit(1);
  }
}

seed();
